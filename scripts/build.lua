local lush = require("lush")

local root = vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":p:h:h")

for name in pairs(package.loaded) do
  if name:match("^baitong%.") then
    package.loaded[name] = nil
  end
end

local palettes = require("baitong.palette")

local variants = vim.tbl_keys(palettes)
table.sort(variants)

for _, variant in ipairs(variants) do
  local p = palettes[variant]
  local compiled = {
    groups = lush.compile(require("baitong.theme")(p, variant)),
    terminal = {
      p.black, p.red, p.green, p.green, p.aqua, p.magenta, p.sky, p.neutral,
      p.comment, p.red, p.fg, p.amber, p.aqua, p.cursor, p.aqua, p.neutral,
    },
  }

  local path = root .. "/lua/baitong/compiled/" .. variant .. ".lua"
  local file = assert(io.open(path, "w"))
  file:write("-- Generated by scripts/build.lua, do not edit\n")
  file:write("return " .. vim.inspect(compiled) .. "\n")
  file:close()
end
